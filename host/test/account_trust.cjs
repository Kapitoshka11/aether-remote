const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { createIdentity } = require('../lib/account/protocol.cjs');
const { createTrustStore } = require('../lib/account/trust-store.cjs');
const { createSecureStore } = require('../lib/account/secure-store.cjs');

(async () => {
  const storage = await createSecureStore({});
  const host = createIdentity(), phone = createIdentity(), stranger = createIdentity();
  const ownerId = crypto.randomUUID();
  const device = { ...phone, ownerId, kind: 'phone' };
  let trust = await createTrustStore(storage, host, ownerId);
  const grant = await trust.approve(device, 'a'.repeat(64));
  assert.equal(trust.isAllowed(grant), true);
  assert.equal(trust.isAllowed({ ...grant, phoneId: stranger.id, phonePublicKeySpki: stranger.publicKeySpki }), false);
  const escaped = trust.find(phone.id, grant.grantId);
  escaped.signature = 'bad';
  assert.equal(trust.isAllowed(grant), true, 'caller cannot mutate stored grants');
  await trust.mergeRevocations([], [{ grant, revokedAt: new Date().toISOString() }]);
  assert.equal(trust.isAllowed(grant), false);
  await trust.mergeRevocations([], []);
  assert.equal(trust.isAllowed(grant), false, 'missing cloud row never restores trust');
  const replacement = await trust.approve(device, 'a'.repeat(64));
  assert.equal(replacement.revision, 2);
  assert.equal(trust.isAllowed(replacement), true);
  trust = await createTrustStore(storage, host, ownerId);
  assert.equal(trust.isAllowed(grant), false);
  assert.equal(trust.isAllowed(replacement), true);
  await trust.revokeDevice(phone.id);
  assert.deepEqual(trust.pendingRevocations(), [phone.id]);
  assert.equal(trust.isAllowed(replacement), false);
  await assert.rejects(trust.approve(device, 'a'.repeat(64)));
  const otherAccount = await createTrustStore(storage, host, crypto.randomUUID());
  assert.equal(otherAccount.isAllowed(replacement), false);
  await trust.clear();
  assert.equal(trust.isAllowed(replacement), false);
  assert.equal((await createTrustStore(storage, host, ownerId)).list().length, 0);
  trust = await createTrustStore(storage, host, ownerId);
  assert.deepEqual(trust.pendingRevocations(), [phone.id], 'logout preserves an offline revocation');
  await trust.acknowledgeRevocation(phone.id);
  assert.deepEqual(trust.pendingRevocations(), []);
  await assert.rejects(trust.approve(device, 'a'.repeat(64)), /account_device_revoked/);
  console.log('account trust: 18 checks passed');
})().catch(error => { console.error(error.message); process.exitCode = 1; });
